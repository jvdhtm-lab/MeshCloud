/// `POST /api/v1/jobs` request body.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SubmitJobRequest {
    /// Workload type the job needs a worker to support.
    pub workload_type: String,
    /// Opaque job input.
    pub input: serde_json::Value,
    /// Job kind. Defaults to `job`; use `agent_task` for delegated work.
    #[serde(default = "default_kind")]
    pub kind: String,
    /// Agent to assign the job to (for agent tasks).
    #[serde(default)]
    pub assignee_agent_id: Option<AgentId>,
    /// Minimum CPU cores required.
    #[serde(default)]
    pub required_cpu_cores: u32,
    /// Minimum RAM (GB) required.
    #[serde(default)]
    pub required_ram_gb: u32,
    /// Maximum attempts before the job is failed.
    #[serde(default = "default_max_attempts")]
    pub max_attempts: u32,
    /// Seconds from now until the job expires.
    #[serde(default = "default_deadline_seconds")]
    pub deadline_seconds: u64,
    /// Maximum delegation depth for this root job.
    #[serde(default)]
    pub max_depth: u32,
    /// Maximum direct children this job may delegate.
    #[serde(default)]
    pub max_fanout: u32,
    /// Budget (credits) available to delegate to children.
    #[serde(default)]
    pub budget_credits: i64,
}

fn default_kind() -> String {
    "job".to_string()
}

fn default_max_attempts() -> u32 {
    3
}

fn default_deadline_seconds() -> u64 {
    3600
}

