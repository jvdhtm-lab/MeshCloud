/// Minimal job summary used by the CLI and API.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct JobView {
    /// Job identifier.
    pub job_id: JobId,
    /// Job kind (`job`, or `agent_task`).
    pub kind: String,
    /// Workload type, e.g. `echo` or `wasm`.
    pub workload_type: String,
    /// Current state.
    pub state: JobState,
    /// Assigned worker, if any.
    pub worker_id: Option<NodeId>,
    /// Assigned agent, if any (for agent tasks).
    pub assignee_agent_id: Option<AgentId>,
    /// Parent job in the delegation DAG, if any.
    pub parent_job_id: Option<JobId>,
    /// Depth in the delegation DAG (0 for the root).
    pub depth: u32,
    /// Budget reserved for this job's children.
    pub budget_credits: i64,
    /// Attempts made so far.
    pub attempts: u32,
    /// Maximum attempts allowed.
    pub max_attempts: u32,
    /// Deadline (RFC 3339).
    pub deadline: chrono::DateTime<chrono::Utc>,
    /// RFC 3339 creation timestamp.
    pub created_at: chrono::DateTime<chrono::Utc>,
    /// Result hash recorded on success, if any.
    pub result_hash: Option<String>,
}

